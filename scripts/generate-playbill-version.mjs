/**
 * Generate worker/playbill-version.ts with the installed
 * @consenttheater/playbill release version baked in. The playbill package
 * `exports` map does not expose its own package.json, so the worker cannot
 * import the version at runtime; we read it from package-lock.json (the
 * reliable, always-present source) and emit a tiny module the worker imports.
 *
 * Runs as the `prebuild` step (see package.json), so the version always tracks
 * the dependency actually installed.
 */
import { readFile, writeFile } from 'node:fs/promises';

const lock = JSON.parse(await readFile('package-lock.json', 'utf8'));
const version =
  lock.packages?.['node_modules/@consenttheater/playbill']?.version ?? 'unknown';

const out = `// Generated by scripts/generate-playbill-version.mjs — do not edit.
export const PLAYBILL_VERSION = '${version}';
`;

await writeFile('worker/playbill-version.ts', out);
console.log(`playbill-version: ${version}`);
